import { test, expect } from '@playwright/test';

test('private collection: browser upload, query, source and version comparison', async ({ page, request }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  const email = `browser-${testInfo.project.name}-${Date.now()}@example.com`;
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('browser-test-only-password');
  await page.getByRole('button', { name: 'Create private workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Ask your knowledge' })).toBeVisible();
  await page.getByRole('button', { name: 'Create your first collection' }).click();
  await page.getByLabel('Collection name').fill('Browser verification');
  await page.getByRole('dialog', { name: 'Create a collection' }).getByRole('button', { name: 'Create collection', exact: true }).click();
  await page.getByRole('button', { name: 'Add your first document' }).click();
  await page.getByLabel('Source version', { exact: true }).fill('v1');
  await page.locator('input[type=file]').setInputFiles({ name: 'browser-guide.md', mimeType: 'text/markdown', buffer: Buffer.from('# Indexing guide\nGIN indexes are preferred for full text search. Use B-tree indexes for equality and range queries.') });
  await expect(page.getByRole('status')).toContainText('accepted');
  await page.getByRole('button', { name: 'Close upload' }).click();
  await expect(page.getByRole('button', { name: /Find the right guidance/ })).toBeVisible();
  await page.getByRole('combobox', { name: 'Answer mode' }).selectOption('evidence');
  await page.getByRole('textbox', { name: 'Ask a question' }).fill('Which GIN indexes support full text search?');
  await page.getByRole('button', { name: 'Send question' }).click();
  await expect(page.getByText('evidence only', { exact: true })).toBeVisible();
  await page.locator('.evidence-card').first().click();
  await expect(page.getByLabel('Source evidence')).toContainText('GIN indexes are preferred');
  await expect(page.getByText('Citation resolved', { exact: true })).toBeVisible();
  await page.screenshot({ path: `../../artifacts/screenshots/${testInfo.project.name}-citation.png`, fullPage: true });
  await page.getByRole('button', { name: 'Close source' }).click();
  await page.getByRole('combobox', { name: 'Answer mode' }).selectOption('generate');
  await page.getByRole('textbox', { name: 'Ask a question' }).fill('Which index type supports full text search?');
  await page.getByRole('button', { name: 'Send question' }).click();
  const generated = page.locator('.message').last();
  await expect(generated.getByText('answered', { exact: true })).toBeVisible({ timeout: 60000 });
  await expect(generated.locator('.answer-text')).toContainText('GIN');
  await generated.getByRole('button', { name: 'Open reference 1' }).click();
  await expect(page.getByLabel('Source evidence')).toContainText('GIN indexes are preferred');
  await page.screenshot({ path: `../../artifacts/screenshots/${testInfo.project.name}-generated-answer.png`, fullPage: true });
  await page.getByRole('button', { name: 'Close source' }).click();
  await page.getByRole('button', { name: 'Document library' }).click();
  await expect(page.getByText('browser-guide.md', { exact: true }).first()).toBeVisible();
  // Version action is also available via keyboard/native titles in the desktop table.
  if (testInfo.project.name === 'desktop') {
    await page.getByTitle('Add a source version').click();
    await page.getByLabel('Source version', { exact: true }).fill('v2');
    await page.locator('input[type=file]').setInputFiles({ name: 'browser-guide.md', mimeType: 'text/markdown', buffer: Buffer.from('# Indexing guide\nGIN indexes support full text search in this second source version. Review query plans before deployment.') });
    await expect(page.getByRole('status')).toContainText('accepted');
    await page.getByRole('button', { name: 'Close upload' }).click();
    await expect(page.getByText('2', { exact: true }).first()).toBeVisible();
    await expect(page.locator('.document-row').getByText('Indexed', { exact: true })).toBeVisible();
    await page.getByTitle('Compare latest two uploaded versions').click();
    await expect(page.getByRole('heading', { name: 'Version v1' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Version v2' })).toBeVisible();
    await page.screenshot({ path: '../../artifacts/screenshots/desktop-versions.png', fullPage: true });
    await page.getByRole('button', { name: 'Close comparison' }).click();
  }
  await page.getByRole('button', { name: 'System health' }).click();
  await expect(page.getByText('SQL prefilter and response recheck')).toBeVisible();
  await page.getByRole('button', { name: 'Evaluations', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No evaluation runs yet' })).toBeVisible();
  await page.getByRole('button', { name: 'Document library' }).click();
  await page.getByTitle('Manage document', { exact: true }).click();
  const manager = page.getByRole('dialog', { name: 'Manage document' });
  await expect(manager).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(manager).not.toBeVisible();
  await page.getByTitle('Manage document', { exact: true }).click();
  const recipientEmail = `reader-${testInfo.project.name}-${Date.now()}@example.com`;
  const registration = await request.post('/api/v1/sessions/register', { data: { email: recipientEmail, password: 'recipient-test-password' } });
  expect(registration.status()).toBe(201);
  await manager.getByLabel('Account email').fill(recipientEmail);
  await manager.getByRole('button', { name: 'Grant read access' }).click();
  await expect(manager.getByRole('status')).toContainText('Read access granted');
  await expect(manager.getByText(recipientEmail, { exact: true })).toBeVisible();
  await manager.getByRole('button', { name: 'Revoke', exact: true }).click();
  await expect(manager.getByRole('status')).toContainText('Read access revoked');
  await manager.getByRole('button', { name: 'Reindex', exact: true }).first().click();
  await expect(manager.getByRole('status')).toContainText('Reindex queued');
  await manager.getByRole('button', { name: 'Delete document…', exact: true }).click();
  await expect(manager.getByRole('button', { name: 'Delete permanently' })).toBeVisible();
  await manager.getByRole('button', { name: 'Keep document' }).click();
  await expect(manager.getByRole('button', { name: 'Delete permanently' })).not.toBeVisible();
  await manager.getByRole('button', { name: 'Delete document…', exact: true }).click();
  await manager.getByRole('button', { name: 'Delete permanently' }).click();
  await expect(manager).not.toBeVisible();
  await expect(page.getByRole('heading', { name: 'No documents yet' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('authentication rejects wrong credentials and preserves error state', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email address').fill('missing@example.com');
  await page.getByLabel('Password', { exact: true }).fill('wrong-password-value');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('invalid credentials');
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeEnabled();
});
